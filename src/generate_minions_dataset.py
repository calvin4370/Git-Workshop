'''
Generates a new minions museum visitor transaction dataset using the
minions_mirage.xlsx dataset generated by Mirage.

Because Mirage has a limited ability to add specific columns and follow
natural distributions, the script will build on the generated dataset to
create a more realistic mock dataset, more closely resembling that of
typical museum visitorship.
'''
import numpy as np
import pandas as pd

# ======================================================================
# Constants
INPUT_DATA_PATH = 'minions_mirage.xlsx'
OUTPUT_DATA_PATH = '../data/minions.xlsx'
SEED = 42
NUM_ROWS = 10000
# ======================================================================

rng = np.random.default_rng(SEED)


# ======================================================================
# Mirage reference
# Read the Mirage dataset once and extract the proportions that later
# column blocks sample from. Nothing below this block reads Mirage directly.
# ======================================================================
mirage = pd.read_excel(INPUT_DATA_PATH)

NAME_PROPORTIONS = mirage['Name'].value_counts(normalize=True)
REDEMPTION_PROPORTIONS = mirage['Redemption Status'].value_counts(normalize=True)
VISIT_DATE_START = pd.to_datetime(mirage['Visit Date']).min()
VISIT_DATE_END = pd.to_datetime(mirage['Visit Date']).max()



# ======================================================================
# Dataset
# Start from an empty frame of NUM_ROWS rows; each block below adds one
# column, in dependency order.
# ======================================================================
df = pd.DataFrame(index=range(NUM_ROWS))


# Add Transaction ID
# Unique ID per ticket transaction, e.g. NHB00001.
df['Transaction ID'] = [f'NHB{i:05d}' for i in range(1, NUM_ROWS + 1)]


# Add Name
# Minion's name, sampled from the Mirage dataset's name frequencies
# (e.g. Bob, Dave and Stuart are the most common).
df['Name'] = rng.choice(NAME_PROPORTIONS.index, size=NUM_ROWS, p=NAME_PROPORTIONS.values)
# print(df['Name'].value_counts(normalize=True).head(10))


# Add Museum
# Museum visited, sampled in proportion to each museum's actual total visits
# over 2024-2025 (NMS ~56%, ACM ~24%, IHC ~12%, TPM ~9%).
# Source: SingStat Table Builder M891071, Visits To Selected Places Of
# Interest, Monthly (thousands), fetched 22 Sep 2026.
# MHC is left out: it was closed for its revamp in 2024-2025.
MONTHLY_VISITS_THOUSANDS = {
    'NMS': {
        2024: [80.4, 99.5, 69.6, 58.3, 68.2, 73.3, 139.7, 155.7, 70, 80, 59.4, 62.7],
        2025: [102.1, 74.8, 53.9, 55, 76.1, 65.9, 119.1, 167.7, 83, 96.5, 65.3, 78.9],
    },
    'ACM': {
        2024: [35.6, 38.8, 37.7, 28.5, 34.7, 33.1, 39.2, 39.3, 25.7, 36.2, 34.1, 22.7],
        2025: [38.4, 37.8, 31.9, 32.3, 49.4, 39.6, 41.3, 40.2, 34.8, 43, 46.4, 29],
    },
    'TPM': {
        2024: [11.6, 13.3, 18.4, 10.5, 13.8, 13.7, 15.3, 23.9, 15.5, 11.9, 10.3, 9.1],
        2025: [11.4, 10.9, 23.8, 18.2, 16.1, 13.7, 13, 22.8, 12, 10.9, 10.7, 9.9],
    },
    'IHC': {
        2024: [24.3, 18.1, 15.5, 20.5, 18.3, 11.3, 22.2, 18.2, 13.7, 43.9, 11, 6.3],
        2025: [20.3, 16.3, 13.3, 19.4, 17.9, 8.6, 22.3, 17.5, 15.1, 38.3, 12.6, 5.9],
    },
}
museum_totals = pd.Series({
    museum: sum(sum(months) for months in years.values())
    for museum, years in MONTHLY_VISITS_THOUSANDS.items()
})
MUSEUM_PROPORTIONS = museum_totals / museum_totals.sum()
df['Museum'] = rng.choice(MUSEUM_PROPORTIONS.index, size=NUM_ROWS, p=MUSEUM_PROPORTIONS.values)
# print(df['Museum'].value_counts(normalize=True))


# Add Nationality
# Hardcoded proportions of nationalities for minions
NATIONALITY_PROPORTIONS = {
    'Singapore': 0.10,
    'PR': 0.08,
    'China': 0.15,
    'Indonesia': 0.10,
    'Malaysia': 0.10,
    'Philippines': 0.09,
    'Japan': 0.14,
    'US': 0.24
}
# Each minion (unique name) has one nationality: build a minions subtable
# with a randomly assigned nationality per name, then join it onto the
# main table by Name.
minions = pd.DataFrame({'Name': NAME_PROPORTIONS.index})
minions['Nationality'] = rng.choice(
    list(NATIONALITY_PROPORTIONS.keys()),
    size=len(minions),
    p=list(NATIONALITY_PROPORTIONS.values()),
)
df = df.merge(minions, on='Name', how='left')
# print(minions['Nationality'].value_counts())
# print(df['Nationality'].value_counts(normalize=True))


# Add Lineitem name (Ticket name)
# Singaporeans and PRs get the local ticket; every other nationality
# gets the foreign/tourist ticket.
df['Lineitem name'] = np.where(
    df['Nationality'].isin(['Singapore', 'PR']),
    'Singaporean/PR',
    'Foreign/Tourist',
)
# print(df['Lineitem name'].value_counts(normalize=True))


# Add Price
# Standard adult admission to permanent galleries (SGD), by museum and
# ticket. Free for Singaporeans/PRs at all NHB museums.
PRICES = {
    'NMS': {'Singaporean/PR': 0, 'Foreign/Tourist': 15},
    'ACM': {'Singaporean/PR': 0, 'Foreign/Tourist': 15},
    'TPM': {'Singaporean/PR': 0, 'Foreign/Tourist': 12},
    'IHC': {'Singaporean/PR': 0, 'Foreign/Tourist': 8},
}
df['Price'] = [PRICES[museum][ticket] for museum, ticket in zip(df['Museum'], df['Lineitem name'])]
# print(df.groupby(['Museum', 'Lineitem name'])['Price'].unique())


# Add Visit Datetime
# Date: sampled over the Mirage date range. Each museum's visits per month
# follow its actual monthly visits (MONTHLY_VISITS_THOUSANDS, above). Within
# a month, weekends and public holidays are ~1.8x busier than weekdays, and
# IHC is closed on Mondays.
# Time: museums open 10am-7pm (last entry 6.30pm). Weekdays have a late-
# morning peak (~11am, school/tour groups) and a mid-afternoon peak (~3pm);
# weekends and public holidays have one broad early-afternoon peak (~2pm).
PUBLIC_HOLIDAYS = pd.to_datetime([
    '2024-01-01', '2024-02-10', '2024-02-11', '2024-02-12', '2024-03-29', '2024-04-10',
    '2024-05-01', '2024-05-22', '2024-06-17', '2024-08-09', '2024-10-31', '2024-12-25',
    '2025-01-01', '2025-01-29', '2025-01-30', '2025-03-31', '2025-04-18', '2025-05-01',
    '2025-05-03', '2025-05-12', '2025-06-07', '2025-08-09', '2025-10-20', '2025-12-25',
])
CLOSED_ON_MONDAYS = ['IHC']
OPENING_HOUR, LAST_ENTRY_HOUR = 10, 18.5

dates = pd.date_range(VISIT_DATE_START, VISIT_DATE_END, freq='D')
is_peak_day = (dates.dayofweek >= 5) | dates.isin(PUBLIC_HOLIDAYS)
date_weights = np.where(is_peak_day, 1.8, 1.0)

visit_dates = np.empty(NUM_ROWS, dtype='datetime64[ns]')
for museum in df['Museum'].unique():
    rows = (df['Museum'] == museum).to_numpy()
    weights = date_weights * ~((dates.dayofweek == 0) & (museum in CLOSED_ON_MONDAYS))
    # Scale each month's days so the month's total weight = its actual visits
    month_visits = np.array([MONTHLY_VISITS_THOUSANDS[museum][d.year][d.month - 1] for d in dates])
    month_weight_sums = pd.Series(weights).groupby(dates.to_period('M')).transform('sum').to_numpy()
    weights = weights / month_weight_sums * month_visits
    visit_dates[rows] = rng.choice(dates, size=rows.sum(), p=weights / weights.sum())
visit_dates = pd.DatetimeIndex(visit_dates)

# Sample hours from the peak(s), redrawing any that fall outside opening hours
is_peak_visit = np.asarray((visit_dates.dayofweek >= 5) | visit_dates.isin(PUBLIC_HOLIDAYS))
visit_hours = np.full(NUM_ROWS, np.nan)
while np.isnan(visit_hours).any():
    todo = np.isnan(visit_hours)
    weekday_peak = rng.choice([0, 1], size=todo.sum(), p=[0.4, 0.6])
    hours = np.where(
        is_peak_visit[todo],
        rng.normal(14.0, 1.9, todo.sum()),
        np.where(weekday_peak == 0, rng.normal(11.2, 0.8, todo.sum()), rng.normal(15.0, 1.3, todo.sum())),
    )
    hours[(hours < OPENING_HOUR) | (hours > LAST_ENTRY_HOUR)] = np.nan
    visit_hours[todo] = hours
df['Visit Datetime'] = visit_dates + pd.to_timedelta(np.round(visit_hours * 3600), unit='s')
# print(df['Visit Datetime'].dt.dayofweek.value_counts().sort_index())
# print(df['Visit Datetime'].dt.hour.value_counts().sort_index())


# Add Source
# Where the ticket was bought: Web (online, in advance), POS (ticketing
# counter) or Kiosk (self-service machine at the museum).
SOURCE_PROPORTIONS = {'Web': 0.5, 'POS': 0.1, 'Kiosk': 0.4}
df['Source'] = rng.choice(
    list(SOURCE_PROPORTIONS.keys()),
    size=NUM_ROWS,
    p=list(SOURCE_PROPORTIONS.values()),
)
# print(df['Source'].value_counts(normalize=True))


# Add Booking Datetime
# Web: booked 0-60 days ahead (most within a week), usually in the evening,
# and always before the visit. POS / Kiosk: bought on arrival, 1-20 minutes
# before entry.
lead_days = np.minimum(rng.geometric(0.2, NUM_ROWS) - 1, 60)
booking_hours = rng.normal(20.5, 2.5, NUM_ROWS) % 24  # late bookings wrap past midnight
web_booking = (df['Visit Datetime'].dt.normalize()
               - pd.to_timedelta(lead_days, unit='D')
               + pd.to_timedelta(np.round(booking_hours * 3600), unit='s'))
# Same-day bookings that land after the visit are redrawn between 7am and
# 10 minutes before entry
visit_seconds = (df['Visit Datetime'] - df['Visit Datetime'].dt.normalize()).dt.total_seconds()
same_day_booking = (df['Visit Datetime'].dt.normalize()
                    + pd.to_timedelta(rng.uniform(7 * 3600, visit_seconds - 600).round(), unit='s'))
web_booking = web_booking.where(web_booking < df['Visit Datetime'], same_day_booking)
onsite_booking = df['Visit Datetime'] - pd.to_timedelta(rng.integers(60, 20 * 60, NUM_ROWS), unit='s')
df['Booking Datetime'] = web_booking.where(df['Source'] == 'Web', onsite_booking)
# print((df['Visit Datetime'] - df['Booking Datetime']).groupby(df['Source']).describe())


# Add Redemption Status
# Whether the ticket was used, sampled per transaction from the Mirage
# dataset's redemption frequencies (~97% Redeemed). Not Redeemed tickets
# are no-shows, so they have no Visit Datetime.
df['Redemption Status'] = rng.choice(REDEMPTION_PROPORTIONS.index, size=NUM_ROWS, p=REDEMPTION_PROPORTIONS.values)
df.loc[df['Redemption Status'] == 'Not Redeemed', 'Visit Datetime'] = pd.NaT
# print(df['Redemption Status'].value_counts(normalize=True))
# print(df.groupby('Redemption Status')['Visit Datetime'].apply(lambda s: s.isna().sum()))



# ======================================================================
# Save
# Write datetimes as 'YYYY-MM-DD HH:MM:SS' text so they display the same in
# any viewer (Excel stores real datetimes as serial numbers, e.g. 45428.65).
# No-show rows keep an empty Visit Datetime.
# ======================================================================
COLUMN_ORDER = [
    'Transaction ID', 'Name', 'Museum', 'Nationality', 'Lineitem name', 'Price',
    'Source', 'Booking Datetime', 'Visit Datetime', 'Redemption Status',
]
for col in ['Visit Datetime', 'Booking Datetime']:
    df[col] = df[col].dt.strftime('%Y-%m-%d %H:%M:%S')
df = df[COLUMN_ORDER]
df.to_excel(OUTPUT_DATA_PATH, index=False)
print(f'Wrote {len(df):,} rows x {df.shape[1]} columns to {OUTPUT_DATA_PATH}')
